import Foundation

/// Writes a mesh as a USDZ package: one mesh prim with smooth vertex normals and a plain
/// UsdPreviewSurface material, Y-up, in centimeters.
public enum USDZWriter {
    public static func write(mesh: Mesh, name: String, color: SIMD3<Double>,
                             surface: ConversionOptions.Surface, to url: URL) throws {
        let usda = makeUSDA(mesh: mesh, name: primName(name), color: color, surface: surface)
        let layer = convertToCrate(usda) ?? (data: Data(usda.utf8), ext: "usda")
        let package = USDZArchive.make(entries: [("\(primName(name)).\(layer.ext)", layer.data)])
        try package.write(to: url, options: .atomic)
    }

    /// USD prim names must be identifiers.
    static func primName(_ s: String) -> String {
        var out = String(s.unicodeScalars.map { CharacterSet.alphanumerics.contains($0) && $0.isASCII ? Character($0) : "_" })
        if out.isEmpty || out.first!.isNumber { out = "_" + out }
        return out
    }

    public static func makeUSDA(mesh: Mesh, name: String, color: SIMD3<Double>,
                                surface: ConversionOptions.Surface) -> String {
        let rgb = "(\(color.x), \(color.y), \(color.z))"
        // Solid: all color comes from emission, so lights add no shading.
        let shaderInputs = surface == .solid
            ? """
                        color3f inputs:diffuseColor = (0, 0, 0)
                                color3f inputs:emissiveColor = \(rgb)
                                float inputs:roughness = 1
                                float inputs:specular = 0
                                int inputs:useSpecularWorkflow = 1
                                color3f inputs:specularColor = (0, 0, 0)
                """
            : """
                        color3f inputs:diffuseColor = \(rgb)
                                float inputs:roughness = 0.5
                """
        let b = mesh.bounds
        var s = ""
        s.reserveCapacity(mesh.positions.count * 70 + mesh.indices.count * 8)
        func f(_ v: Float) -> String { v == v.rounded() ? String(Int(v)) : String(v) }
        func f3(_ v: SIMD3<Float>) -> String { "(\(f(v.x)), \(f(v.y)), \(f(v.z)))" }

        s += """
        #usda 1.0
        (
            defaultPrim = "\(name)"
            metersPerUnit = 0.01
            upAxis = "Y"
            doc = "Generated by Tubeline"
        )

        def Xform "\(name)" (
            kind = "component"
        )
        {
            def Mesh "Geometry" (
                prepend apiSchemas = ["MaterialBindingAPI"]
            )
            {
                float3[] extent = [(\(b.min.x), \(b.min.y), \(b.min.z)), (\(b.max.x), \(b.max.y), \(b.max.z))]
                int[] faceVertexCounts = [
        """
        s += Array(repeating: "3", count: mesh.triangleCount).joined(separator: ",")
        s += "]\n        int[] faceVertexIndices = ["
        s += mesh.indices.map(String.init).joined(separator: ",")
        s += "]\n        point3f[] points = ["
        s += mesh.positions.map(f3).joined(separator: ",")
        s += "]\n        normal3f[] normals = ["
        s += mesh.normals.map(f3).joined(separator: ",")
        s += """
        ] (
                    interpolation = "vertex"
                )
                uniform token orientation = "rightHanded"
                uniform token subdivisionScheme = "none"
                uniform bool doubleSided = 0
                rel material:binding = </\(name)/Materials/Surface>
            }

            def Scope "Materials"
            {
                def Material "Surface"
                {
                    token outputs:surface.connect = </\(name)/Materials/Surface/PreviewSurface.outputs:surface>

                    def Shader "PreviewSurface"
                    {
                        uniform token info:id = "UsdPreviewSurface"
                \(shaderInputs)
                        float inputs:metallic = 0
                        token outputs:surface
                    }
                }
            }
        }

        """
        return s
    }

    /// Converts text USD to the binary crate format with macOS's bundled `usdcat`, if available.
    /// Binary layers are much smaller and are what Apple's own tools produce.
    static func convertToCrate(_ usda: String) -> (data: Data, ext: String)? {
        let tool = URL(fileURLWithPath: "/usr/bin/usdcat")
        guard FileManager.default.isExecutableFile(atPath: tool.path) else { return nil }
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("tubeline-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: dir) }
        do {
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            let input = dir.appendingPathComponent("in.usda"), output = dir.appendingPathComponent("out.usdc")
            try Data(usda.utf8).write(to: input)
            let p = Process()
            p.executableURL = tool
            p.arguments = [input.path, "-o", output.path]
            p.standardOutput = FileHandle.nullDevice
            p.standardError = FileHandle.nullDevice
            try p.run()
            p.waitUntilExit()
            guard p.terminationStatus == 0 else { return nil }
            return (try Data(contentsOf: output), "usdc")
        } catch {
            return nil
        }
    }
}

/// Minimal writer for USDZ packages: an uncompressed zip whose file data is 64-byte aligned.
enum USDZArchive {
    static func make(entries: [(name: String, data: Data)]) -> Data {
        var out = Data()
        var central = Data()
        for (name, data) in entries {
            let nameBytes = Data(name.utf8)
            let headerOffset = out.count
            let crc = crc32(data)
            // Pad with an extra field so the file data starts on a 64-byte boundary.
            let base = headerOffset + 30 + nameBytes.count
            var pad = (64 - base % 64) % 64
            if pad > 0 && pad < 4 { pad += 64 }

            out.le32(0x0403_4B50)
            out.le16(20); out.le16(0); out.le16(0)  // version, flags, method (stored)
            out.le16(0); out.le16(0x21)             // time, date (1980-01-01)
            out.le32(crc); out.le32(UInt32(data.count)); out.le32(UInt32(data.count))
            out.le16(UInt16(nameBytes.count)); out.le16(UInt16(pad))
            out.append(nameBytes)
            if pad > 0 {
                out.le16(0x1986); out.le16(UInt16(pad - 4))
                out.append(Data(count: pad - 4))
            }
            out.append(data)

            central.le32(0x0201_4B50)
            central.le16(20); central.le16(20); central.le16(0); central.le16(0)
            central.le16(0); central.le16(0x21)
            central.le32(crc); central.le32(UInt32(data.count)); central.le32(UInt32(data.count))
            central.le16(UInt16(nameBytes.count)); central.le16(0); central.le16(0)
            central.le16(0); central.le16(0); central.le32(0)
            central.le32(UInt32(headerOffset))
            central.append(nameBytes)
        }
        let centralOffset = out.count
        out.append(central)
        out.le32(0x0605_4B50)
        out.le16(0); out.le16(0)
        out.le16(UInt16(entries.count)); out.le16(UInt16(entries.count))
        out.le32(UInt32(central.count)); out.le32(UInt32(centralOffset))
        out.le16(0)
        return out
    }

    private static let table: [UInt32] = (0..<256).map { i in
        var c = UInt32(i)
        for _ in 0..<8 { c = (c & 1) != 0 ? 0xEDB8_8320 ^ (c >> 1) : c >> 1 }
        return c
    }

    static func crc32(_ data: Data) -> UInt32 {
        var c: UInt32 = 0xFFFF_FFFF
        for byte in data { c = table[Int((c ^ UInt32(byte)) & 0xFF)] ^ (c >> 8) }
        return c ^ 0xFFFF_FFFF
    }
}

private extension Data {
    mutating func le16(_ v: UInt16) { Swift.withUnsafeBytes(of: v.littleEndian) { append(contentsOf: $0) } }
    mutating func le32(_ v: UInt32) { Swift.withUnsafeBytes(of: v.littleEndian) { append(contentsOf: $0) } }
}
